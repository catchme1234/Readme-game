// Повторяющиеся ссоры: если пара в третий раз говорит об одной теме,
// бот предлагает поговорить о теме целиком, а не о последнем случае.
export const REPEAT_AT = 3;

// Сколько разговоров на эту тему уже было (включая текущий, если он есть).
export function repeatCount(pair, topic) {
  if (!topic || topic === 'other') return 0;
  return (pair.talks || []).filter((t) => t.topic === topic).length + (pair.talk?.topic === topic ? 1 : 0);
}

// Вопросы о теме целиком. {topic} заменяется на название темы в нижнем регистре.
export const THEME_Q = {
  gentle: [
    'Мы уже не первый раз спорим про «{topic}». Что для тебя в этой теме самое больное?',
    'Как ты думаешь, почему мы возвращаемся к этому снова и снова?',
    'Что в «{topic}» у нас уже получается, даже если мы спорим?',
  ],
  playful: [
    'Если бы наш спор про «{topic}» был сериалом, как бы назывался следующий сезон?',
    'Какое одно правило про «{topic}» мы могли бы записать на холодильник?',
    'Если бы мы были соседями, а не парой, как бы мы договорились про «{topic}»?',
  ],
  deep: [
    'Что «{topic}» значит для тебя глубже, чем сам предмет спора?',
    'Как в твоей семье в детстве относились к теме «{topic}»?',
    'Чего ты боишься, что случится, если мы так и не договоримся про «{topic}»?',
  ],
};

export const themeQuestions = (tone, topicLabel) =>
  (THEME_Q[tone] || THEME_Q.gentle).map((q) => q.replaceAll('{topic}', topicLabel.toLowerCase()));
