// Безопасность: если в словах есть признаки насилия, угроз или мыслей о самоповреждении,
// игра для этого человека останавливается, а партнёр ничего не получает.
// Это грубый фильтр по словам: лучше лишний раз мягко спросить, чем пропустить.

const PATTERNS = [
  // насилие и угрозы
  /(меня бь[её]т|бь[её]т меня|бь[её]шь меня|избил|избила|избива|ударил меня|ударила меня|меня ударил|меня ударила|ударит меня|поднял на меня руку|подняла на меня руку|душил меня|душила меня|толкнул меня|толкнула меня)/i,
  /(убью|прибью|покалечу|зарежу|застрелю|пристрелю) (тебя|его|е[её]|вас|себя)|(тебя|его|е[её]|вас) (убью|прибью|покалечу|зарежу|застрелю|пристрелю)|убить тебя|убь[её]т меня/i,
  /(угрожа|запугива|держит взаперти|не выпускает из дома|отбирает телефон|отбира[ею]т деньги)/i,
  /(изнасил|принуждает к сексу|заставля[ею]т? (меня )?(заниматься )?сексом)/i,
  /(боюсь за свою жизнь|боюсь,? что (он|она) (меня )?(ударит|убь[её]т)|мне страшно находиться дома)/i,
  // самоповреждение
  /(покончить с собой|покончу с собой|суицид|не хочу жить|убить себя|убью себя|порезать себя|режу себя|наложить на себя руки)/i,
];

export function flagged(...texts) {
  const t = texts.filter(Boolean).join('\n').replace(/ё/g, 'е').replace(/Ё/g, 'Е');
  const raw = texts.filter(Boolean).join('\n');
  return PATTERNS.some((re) => re.test(raw) || re.test(t));
}

